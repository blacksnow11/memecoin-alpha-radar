// Helper to filter and sort wallets strictly from most profitable to least profitable
function getRankedWallets(chain, timeframe = 'all', sortBy = 'profit') {
    let list = [...exports.SEED_WALLETS];
    if (chain && chain !== 'all') {
        list = list.filter((w) => w.chain === chain);
    }
    // Adjust for timeframe scaling factor
    const timeframeMultiplier = {
        '24h': 0.08,
        '7d': 0.32,
        '30d': 0.85,
        'all': 1.0,
    }[timeframe];
    // Map profit according to timeframe
    const adjusted = list.map((w) => ({
        ...w,
        totalNetProfitUsd: Math.round(w.totalNetProfitUsd * timeframeMultiplier),
        totalNetProfitNative: +(w.totalNetProfitNative * timeframeMultiplier).toFixed(1),
    }));
    // Sort
    if (sortBy === 'profit') {
        adjusted.sort((a, b) => b.totalNetProfitUsd - a.totalNetProfitUsd);
    }
    else if (sortBy === 'winrate') {
        adjusted.sort((a, b) => b.winRate - a.winRate);
    }
    else if (sortBy === 'alpha') {
        adjusted.sort((a, b) => b.alphaScore - a.alphaScore);
    }
    // Re-index ranks
    return adjusted.map((w, idx) => ({ ...w, rank: idx + 1 }));
}
// Find a single wallet profile by address or generate dynamic inspection profile
function getWalletByAddress(address) {
    const found = exports.SEED_WALLETS.find((w) => w.address.toLowerCase() === address.toLowerCase());
    if (found)
        return found;
    // If not found in seed, dynamically analyze and generate a forensic profile for any arbitrary address!
    return generateDynamicWalletProfile(address);
}
